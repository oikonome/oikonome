// Expo config plugin: Android manifest hardening that app.json cannot
// express on its own. mobile/android/ is a prebuild output (gitignored),
// so anything that must survive `expo prebuild --clean` has to be
// generated from here.
//
//  - android:networkSecurityConfig → res/xml/network_security_config.xml.
//    Cleartext HTTP is what a self-hosted box on a home LAN speaks, and
//    Android's config matches hostnames, not address ranges, so the
//    platform file cannot say "http only for RFC1918". It therefore
//    permits cleartext at the base and pins trust to the SYSTEM CA store
//    (no user-installed CAs, so a proxy certificate someone talked a
//    person into installing cannot read the https traffic); the
//    private-range rule for http:// is enforced where the address is
//    typed (src/lib/pure.ts serverUrlVerdict — refuses public hosts,
//    warns on private ones). android:usesCleartextTraffic is left off:
//    once a network security config exists, the config governs.
const { AndroidConfig, withAndroidManifest,
        withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by plugins/with-android-hardening.js — edit there -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withNetworkSecurityConfig(config) {
  config = withDangerousMod(config, ["android", async (c) => {
    const dir = path.join(c.modRequest.platformProjectRoot,
                          "app", "src", "main", "res", "xml");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "network_security_config.xml"),
                     NETWORK_SECURITY_CONFIG);
    return c;
  }]);
  return withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app && app.$) {
      app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
      delete app.$["android:usesCleartextTraffic"];
    }
    return c;
  });
}

module.exports = function withAndroidHardening(config) {
  return withNetworkSecurityConfig(config);
};
