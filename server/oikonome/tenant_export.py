def has_live_consent(admin, tenant_id: str,
                     now: dt.datetime | None = None) -> bool:
    now = now or dt.datetime.now(dt.timezone.utc)
    row = admin.execute(
        """SELECT 1 FROM support_consents
           WHERE tenant_id=%s AND revoked_at IS NULL AND expires_at > %s
           LIMIT 1""", (tenant_id, now)).fetchone()
    return row is not None


def consent_status(admin, tenant_id: str,
                   now: dt.datetime | None = None) -> dict | None:
    """The live grant's expiry + reason for the console, or None."""
    now = now or dt.datetime.now(dt.timezone.utc)
    row = admin.execute(
        """SELECT reason, expires_at, created_at FROM support_consents
           WHERE tenant_id=%s AND revoked_at IS NULL AND expires_at > %s
           ORDER BY expires_at DESC LIMIT 1""",
        (tenant_id, now)).fetchone()
    return dict(row) if row else None
