"""Every password compose pastes into a connection URL is one a URL can
carry as typed.

compose.yaml builds the database and job-queue URLs by pasting the
password from docker/.env between `:` and `@`. A '/', '@', '%' or space
there moves the host or the port (or fails to decode), and the app and
worker then fail at start with a host or port error that never mentions
the password. So the installer generates every such password from a
URL-safe alphabet, and docker/.env.example tells anyone filling it by hand
which characters are safe. Reads the files as text."""

import re
import unittest
from pathlib import Path

APP = Path(__file__).resolve().parents[2]


def _pasted_into_urls() -> set[str]:
    src = (APP / "docker/compose.yaml").read_text()
    return set(re.findall(r"://[\w-]*:\$\{(\w+)", src))


class PasswordsPastedIntoUrlsAreUrlSafe(unittest.TestCase):

    def test_parser_sees_the_pasted_passwords(self):
        self.assertTrue({"OIKONOME_APP_PASSWORD", "REDIS_PASSWORD"}
                        <= _pasted_into_urls())

    def test_the_installer_generates_each_from_hex(self):
        src = (APP / "install.sh").read_text()
        rand = re.search(r"rand\(\)\s*\{\s*([^}]*)\}", src)
        self.assertIsNotNone(rand)
        self.assertIn("openssl rand -hex", rand.group(1))
        for var in _pasted_into_urls():
            gen = re.findall(rf'set_env {var} "\$\(([^)]*)\)"', src)
            self.assertTrue(gen, f"install.sh never generates {var}")
            for g in gen:
                self.assertTrue(g == "rand" or "openssl rand -hex" in g,
                                f"{var} generated by {g!r}")

    def test_the_example_names_the_safe_characters_beside_each(self):
        src = (APP / "docker/.env.example").read_text()
        note = re.search(r"# Hand-filled passwords:(.*?)\n(?!#)", src, re.S)
        self.assertIsNotNone(note, ".env.example says nothing about which "
                                   "characters a password may hold")
        text = note.group(1)
        for ch in ("/", "@", "%", "#", "?"):
            self.assertIn(f"'{ch}'", text, ch)
        after = src[note.end():]
        for var in _pasted_into_urls():
            self.assertRegex(after, rf"(?m)^{var}=", var)


if __name__ == "__main__":
    unittest.main()
