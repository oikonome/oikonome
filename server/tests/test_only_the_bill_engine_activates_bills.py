"""Only the bill engine creates bills or makes one active.

The bill writers in engine/bills.py refuse to write inside a transaction
that does not hold the household's bill-claim lock, which is what keeps
two writers from both claiming one charge. A raw INSERT or an UPDATE that
sets active elsewhere would walk round that guard, so this reads every
SQL string in the package and allows them only in the engine.

The one exception is the backup restore, which re-creates the bills it
carries under the sync lock and its own write locks: asking for the claim
lock there would come after those, the inversion the lock order forbids.
Its write is generated by a declared lander (sync/landers.py), so the
landers' SQL is read as that file's strings. The allowlists only ever
shrink.
"""

import ast
import pathlib
import re
import unittest

from .util import api_file_of

PKG = pathlib.Path(__file__).resolve().parent.parent / "oikonome"
ENGINE = "engine/bills.py"

LANDERS_FILE = "sync/landers.py"
INSERTS_ALLOWED = {ENGINE, LANDERS_FILE}
ACTIVATES_ALLOWED = {ENGINE}
# the claim lock taken by hand instead of through bills.bill_write; the
# JSON bill doors still take it this way and move to bill_write later
# (whichever API module holds them — see util.api_file_of)
RAW_CLAIM_ALLOWED = {ENGINE, "web/" + api_file_of("_hold_bill_claims")}

_INSERT = re.compile(r"\bINSERT\s+INTO\s+bills\b(?!_)", re.I)
_ACTIVATE = re.compile(
    r"\bUPDATE\s+bills\b(?!_)[^;]*?\bSET\b[^;]*?(?<![\w.])active\s*=\s*"
    r"(1|true)\b", re.I | re.S)


def _strings(tree):
    """Every string literal, an f-string read with its holes blanked."""
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            yield node.value
        elif isinstance(node, ast.JoinedStr):
            yield "".join(v.value if isinstance(v, ast.Constant) else " ? "
                          for v in node.values)


def _calls(tree, name):
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            f = node.func
            if (isinstance(f, ast.Attribute) and f.attr == name) or (
                    isinstance(f, ast.Name) and f.id == name):
                yield node.lineno


class OnlyTheBillEngineActivatesBillsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.trees = {}
        for p in sorted(PKG.rglob("*.py")):
            rel = p.relative_to(PKG).as_posix()
            cls.trees[rel] = ast.parse(p.read_text(), filename=str(p))

    def _where(self, pattern):
        from oikonome.sync.landers import LANDERS
        generated = [lander.sql for lander in LANDERS.values()]
        return {rel for rel, tree in self.trees.items()
                if any(pattern.search(s) for s in (
                    *_strings(tree),
                    *(generated if rel == LANDERS_FILE else ())))}

    def test_the_restore_writes_bills_through_its_bills_lander_only(self):
        from oikonome.sync.landers import LANDERS
        self.assertEqual({t for t, lander in LANDERS.items()
                          if _INSERT.search(lander.sql)}, {"bills"})
        self.assertIn(LANDERS_FILE, self._where(_INSERT))

    def test_the_checks_see_the_engine_itself(self):
        """A pattern that matches nothing would pass vacuously."""
        self.assertIn(ENGINE, self._where(_INSERT))
        self.assertIn(ENGINE, self._where(_ACTIVATE))
        self.assertTrue(list(_calls(self.trees[ENGINE], "hold_bill_claims")))

    def test_bills_are_inserted_only_by_the_engine_and_the_restore(self):
        self.assertLessEqual(self._where(_INSERT), INSERTS_ALLOWED)

    def test_only_the_engine_sets_a_bill_active(self):
        self.assertLessEqual(self._where(_ACTIVATE), ACTIVATES_ALLOWED)

    def test_the_claim_lock_is_taken_through_bill_write_elsewhere(self):
        raw = {rel for rel, tree in self.trees.items()
               if list(_calls(tree, "hold_bill_claims"))}
        self.assertLessEqual(raw, RAW_CLAIM_ALLOWED)


if __name__ == "__main__":
    unittest.main()
